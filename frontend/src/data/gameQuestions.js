/**
 * Motor de rotación dinámico sin repeticiones diarias.
 * Garantiza que cada día el usuario reciba preguntas aleatorias, distintas y frescas,
 * excluyendo las preguntas que ya completó en días recientes.
 */
export function getDailyGameQuestions(gameType, count, userId = '') {
  const todayStr = new Date().toISOString().split('T')[0];
  const sessionCacheKey = `intimos_daily_session_${gameType}_${todayStr}_${userId}`;
  const historyKey = `intimos_seen_history_${gameType}_${userId}`;

  // 1. Si ya se generó la sesión de hoy para este usuario, la devolvemos para mantener coherencia
  try {
    const cached = localStorage.getItem(sessionCacheKey);
    if (cached) {
      const parsed = JSON.parse(cached);
      if (Array.isArray(parsed) && parsed.length >= count) {
        return parsed;
      }
    }
  } catch (e) {}

  // 2. Seleccionar el banco correspondiente
  let pool = [];
  switch (gameType) {
    case 'verso_flash':
      pool = VERSO_FLASH;
      break;
    case 'que_harias':
      pool = QUE_HARIAS;
      break;
    case 'reto_60':
      pool = RETO_60;
      break;
    case 'verdadero_falso':
      pool = VERDADERO_FALSO;
      break;
    case 'ahorcado':
      pool = AHORCADO_BIBLICO;
      break;
    case 'ordena_verso':
      pool = ORDENA_VERSICULO;
      break;
    default:
      pool = [];
  }

  if (!pool || pool.length === 0) return [];

  // Función para obtener identificador único
  const getId = (item, idx) => item.id || item.word || item.q || item.ref || String(idx);

  // 3. Leer historial de preguntas vistas recientemente
  let seenIds = [];
  try {
    const rawSeen = localStorage.getItem(historyKey);
    if (rawSeen) seenIds = JSON.parse(rawSeen);
  } catch (e) {}

  // 4. Filtrar preguntas que NO han sido vistas recientemente
  let available = pool.filter((item, idx) => !seenIds.includes(getId(item, idx)));

  // Si el banco no visto tiene menos preguntas de las requeridas, reiniciamos el historial
  if (available.length < count) {
    seenIds = [];
    available = [...pool];
  }

  // 5. Barajado Fisher-Yates de alta entropía
  const shuffled = [...available];
  for (let i = shuffled.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
  }

  const selected = shuffled.slice(0, count);

  // 6. Actualizar historial de vistas y caché de sesión diaria
  try {
    const newlySeenIds = selected.map((item, idx) => getId(item, idx));
    const updatedHistory = [...seenIds, ...newlySeenIds];
    // Conservamos un historial suficiente para no repetir durante varios días
    const maxRetention = Math.max(pool.length - count, count);
    const trimmedHistory = updatedHistory.slice(-maxRetention);
    localStorage.setItem(historyKey, JSON.stringify(trimmedHistory));
    localStorage.setItem(sessionCacheKey, JSON.stringify(selected));
  } catch (e) {}

  return selected;
}
